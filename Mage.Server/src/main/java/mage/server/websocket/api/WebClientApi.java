package mage.server.websocket.api;

import mage.server.websocket.rpc.RpcDispatcher;
import mage.server.websocket.rpc.RpcMethod;

import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;

/**
 * Web client bridge: every RPC method the web client can call.
 */
public final class WebClientApi {

    private WebClientApi() {
    }

    public static RpcDispatcher createDispatcher(ApiContext ctx) {
        RpcDispatcher dispatcher = new RpcDispatcher(ctx.sessions);
        for (List<RpcMethod> methods : groups(ctx).values()) {
            dispatcher.registerAll(methods);
        }
        return dispatcher;
    }

    /**
     * The methods by group, in registration order. A group is one {@code *Api} class, named after it ("Session",
     * "CareerModes"); the Rust gateway routes calls by group (rust/crates/playmat-protocol/methods.json, generated by
     * WebClientApiDocsTest).
     */
    public static Map<String, List<RpcMethod>> groups(ApiContext ctx) {
        Map<String, List<RpcMethod>> groups = new LinkedHashMap<>();
        groups.put("Session", SessionApi.methods(ctx));
        groups.put("Catalog", CatalogApi.methods(ctx));
        groups.put("DeckImport", DeckImportApi.methods(ctx));
        groups.put("Lobby", LobbyApi.methods(ctx));
        groups.put("Game", GameApi.methods(ctx));
        groups.put("Event", EventApi.methods(ctx));
        groups.put("Admin", AdminApi.methods(ctx));
        groups.put("Access", AccessApi.methods(ctx));
        groups.put("Staff", StaffApi.methods(ctx));
        groups.put("Accounts", AccountsApi.methods(ctx));
        groups.put("Settings", SettingsApi.methods(ctx));
        groups.put("Account", AccountApi.methods(ctx));
        groups.put("MyAccount", MyAccountApi.methods(ctx));
        groups.put("Support", SupportApi.methods(ctx));
        groups.put("Career", CareerApi.methods(ctx));
        groups.put("CareerProgress", CareerProgressApi.methods(ctx));
        groups.put("CareerModes", CareerModesApi.methods(ctx));
        groups.put("Solo", SoloApi.methods(ctx));
        return groups;
    }
}

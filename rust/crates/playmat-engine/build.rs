//! Registers the per-card handlers (docs/rust/Engine.md, "Per-card handlers"): every `.rs` file under `src/cards/`
//! except `mod.rs` is a module of `rules::cards`, and its `HANDLERS` join the registry. Adding a card is adding a
//! file; nobody edits a shared list.

use std::fmt::Write as _;
use std::path::{Path, PathBuf};

fn handler_files(dir: &Path, out: &mut Vec<PathBuf>) {
    let Ok(entries) = std::fs::read_dir(dir) else { return };
    for entry in entries.flatten() {
        let path = entry.path();
        if path.is_dir() {
            println!("cargo:rerun-if-changed={}", path.display());
            handler_files(&path, out);
        } else if path.extension().is_some_and(|e| e == "rs") && path.file_name().is_some_and(|n| n != "mod.rs") {
            out.push(path);
        }
    }
}

fn main() {
    let dir = PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").unwrap()).join("src").join("cards");
    println!("cargo:rerun-if-changed={}", dir.display());
    let mut files = Vec::new();
    handler_files(&dir, &mut files);
    // the order modules are listed in doesn't matter (handlers are found by name), but keep the output stable
    files.sort();
    let mut code = String::from("// generated by build.rs from the files under src/cards/\n");
    let mut names = Vec::new();
    for f in &files {
        let rel = f.strip_prefix(&dir).unwrap().with_extension("");
        let name: String =
            rel.components().map(|c| c.as_os_str().to_string_lossy().into_owned()).collect::<Vec<_>>().join("__");
        assert!(
            name.chars().all(|c| c.is_ascii_lowercase() || c.is_ascii_digit() || c == '_')
                && name.starts_with(|c: char| c.is_ascii_lowercase()),
            "src/cards/{}: a handler file's name must be snake_case (the card's name, as `etali_primal_storm.rs`)",
            rel.display()
        );
        println!("cargo:rerun-if-changed={}", f.display());
        writeln!(code, "#[path = {:?}]\nmod {};", f.display().to_string(), name).unwrap();
        names.push(name);
    }
    code.push_str("\n/// every handler file's `HANDLERS`\npub(crate) const ALL: &[&[Handler]] = &[\n");
    for n in &names {
        writeln!(code, "    {}::HANDLERS,", n).unwrap();
    }
    code.push_str("];\n");
    let out = PathBuf::from(std::env::var("OUT_DIR").unwrap()).join("card_handlers.rs");
    std::fs::write(out, code).unwrap();
}
